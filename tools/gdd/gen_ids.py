"""Generate docs/gdd/ids.md: where each GDD ID is defined.

Usage: python tools/gdd/gen_ids.py   (exit 1 if any expected ID has no defining table row)
An ID is "defined" by a Markdown table row whose first cell starts with it (or with a
range such as "LV01–LV05"); single-ID rows win over range rows.
"""
import re
import sys
from pathlib import Path

GDD = Path(__file__).resolve().parents[2] / "docs/gdd"


def ids(prefix, n, width=2, sep=""):
    return [f"{prefix}{sep}{i:0{width}d}" for i in range(1, n + 1)]


# The GDD has no LV06-LV13: LV01-LV05 are the arena layouts (9.5); the 13-member
# level family is LD01-LD13 (9.6 level validation).
FAMILIES = {
    "F (session stages)": ids("F", 9),
    "O (objects)": ids("O", 12),
    "PF (fighter properties)": ids("PF", 8),
    "H (hazards)": ids("H", 7),
    "T (acceptance tests)": ids("T", 20),
    "AI (bot tests)": ids("AI", 6, 1, "-"),
    "LV (arena layouts)": ids("LV", 5),
    "LD (level validation)": ids("LD", 13),
    "B (cutscenes and cards)": ids("B", 10),
}
FIRST = re.compile(r"^((?:AI-|[A-Z]{1,2})\d+[a-z]?)(?:[–-]((?:AI-|[A-Z]{1,2})\d+))?\b\s*(.*)$")


def anchor(heading, seen):
    a = re.sub(r"[^\w\- ]", "", heading.lower()).replace(" ", "-")
    n = seen.get(a, 0)
    seen[a] = n + 1
    return a if n == 0 else f"{a}-{n}"


def expand(a, b):
    if not b:
        return [a]
    pre, x, y = re.match(r"(\D+)(\d+)", a)[1], int(re.match(r"\D+(\d+)", a)[1]), int(re.match(r"\D+(\d+)", b)[1])
    width = len(re.match(r"\D+(\d+)", a)[1])
    return [f"{pre}{i:0{width}d}" for i in range(x, y + 1)]


def scan():
    found = {}  # id -> (is_range, file, anchor, summary)
    for f in sorted(GDD.glob("*.md")):
        if f.name in ("ids.md", "README.md"):
            continue
        seen, where = {}, ""
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.startswith("#"):
                where = anchor(line.lstrip("#").strip(), seen)
            elif line.startswith("| ") and not line.startswith("|---"):
                cells = [c.strip() for c in re.split(r"(?<!\\)\|", line)[1:-1]]
                m = FIRST.match(cells[0])
                if not m:
                    continue
                a, b, rest = m.groups()
                summary = " — ".join(c for c in [rest] + cells[1:] if c)
                summary = summary if len(summary) <= 100 else summary[:99].rstrip() + "…"
                for i in expand(a, b):
                    if i not in found or (found[i][0] and not b):
                        found[i] = (bool(b), f.name, where, summary)
    return found


def main():
    found = scan()
    out = ["# GDD ID index", "",
           "Generated by `python tools/gdd/gen_ids.py`. Do not hand-edit; fix the chapter files and re-run.", "",
           "**LV vs LD:** two different level families, not one.", "",
           "- **LV01–LV05** = the five arena layouts and their configurations (L1–L5), content inventory GDD 9.5.",
           "- **LD01–LD13** = level validation checks every arena must pass (spawns, tutorial, readability, …), GDD 9.6.",
           "- There is no LV06–LV13: the A02 setup brief's \"LV01–LV13\" meant LV01–LV05 plus LD01–LD13.", ""]
    missing = []
    for fam, members in FAMILIES.items():
        out += [f"## {fam}", "", "| ID | Where | Summary |", "|---|---|---|"]
        for i in members:
            subs = sorted(k for k in found if re.fullmatch(re.escape(i) + "[a-z]", k))
            if i not in found and not subs:
                missing.append(i)
                continue
            # F03 exists only as sub-stages F03a/F03b/F03c in Figure 2
            _, name, where, summary = found[i] if i in found else found[subs[0]]
            if i not in found:
                summary = f"(as {', '.join(subs)}) {summary}"[:100]
            out.append(f"| {i} | [{name}#{where}]({name}#{where}) | {summary} |")
        out.append("")
    (GDD / "ids.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {GDD / 'ids.md'}: {sum(map(len, FAMILIES.values())) - len(missing)} IDs")
    if missing:
        print("MISSING:", ", ".join(missing), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    assert anchor("6.1 Design quantities and initial balance values", {}) == "61-design-quantities-and-initial-balance-values"
    assert expand("LV01", "LV05")[-1] == "LV05" and expand("B02", "B06") == ["B02", "B03", "B04", "B05", "B06"]
    main()
