#!/usr/bin/env python3
"""Claude Code PreToolUse guard. Exit 2 (block) on:
- file writes into Unity-generated folders (Library/, Temp/, Logs/, UserSettings/);
- recursive deletes whose target is not under Temp/.
Reads the hook JSON from stdin. Must stay fast (< 100 ms).
"""
import json
import os
import re
import shlex
import sys

FORBIDDEN = ("Library", "Temp", "Logs", "UserSettings")
ROOT = os.environ.get("CLAUDE_PROJECT_DIR", os.getcwd()).replace("\\", "/").rstrip("/").lower()
RECURSIVE_RM = re.compile(r"\brm\s+(-\w*r\w*|--recursive)|\bRemove-Item\b.*-Recurse|\brmdir\s+/s|\brd\s+/s", re.I)


def rel(path: str) -> str:
    p = path.replace("\\", "/")
    if p.lower().startswith(ROOT + "/"):
        p = p[len(ROOT) + 1:]
    elif re.match(r"^/[a-z]/", p) and ("/" + ROOT[0] + ROOT[2:]).lower() + "/" in p.lower():  # Git Bash /d/...
        p = p.lower().split(ROOT[2:] + "/", 1)[-1]
    return p.lstrip("./")


def block(msg: str) -> None:
    print(f"Blocked by tools/hooks/guard.py: {msg}", file=sys.stderr)
    sys.exit(2)


def main() -> None:
    data = json.load(sys.stdin)
    tool, inp = data.get("tool_name", ""), data.get("tool_input", {}) or {}
    path = inp.get("file_path") or inp.get("notebook_path")
    if path and tool in ("Write", "Edit", "MultiEdit", "NotebookEdit"):
        top = rel(path).split("/", 1)[0]
        if top in FORBIDDEN:
            block(f"{top}/ is generated by Unity; never edit it. Change the source asset or setting instead.")
    cmd = inp.get("command", "")
    if tool in ("Bash", "PowerShell") and RECURSIVE_RM.search(cmd):
        try:
            words = shlex.split(cmd, posix=tool == "Bash")
        except ValueError:
            words = cmd.split()
        targets = [w for w in words[1:] if not w.startswith("-") and w.lower() not in ("rm", "remove-item", "rmdir", "rd", "/s", "/q")]
        if not targets or any(not rel(t.strip("'\"")).startswith("Temp/") for t in targets):
            block("recursive delete outside Temp/. Delete specific files, or ask the user to run it.")


if __name__ == "__main__":
    main()
